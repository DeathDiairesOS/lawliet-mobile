"""Replaceable external investigation engines. Not an agent framework."""
from typing import Protocol


class InvestigationEngine(Protocol):
    def check_availability(self, config: dict) -> dict: ...
    def get_capabilities(self) -> dict: ...
    def start_investigation(self, config: dict) -> dict: ...
    def get_status(self, job_id: str) -> dict: ...
    def cancel_investigation(self, job_id: str) -> dict: ...
    def get_results(self, job_id: str) -> dict: ...
    def get_logs(self, job_id: str) -> dict: ...


def engine(workspace, case, name='mulder') -> InvestigationEngine:
    if name != 'mulder':
        from .core import UserError
        raise UserError('Unsupported investigation engine.')
    from .mulder_engine import MulderEngine
    return MulderEngine(workspace, case)
